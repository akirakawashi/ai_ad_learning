"""Настройки классификации брендов. Все числа живут здесь."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from adlearn import paths

BRANDS = ("beeline", "megafon", "tele2", "other")
"""Порядок классов фиксирован: по нему нумеруются метки и строки confusion matrix.

`other` — полноправный класс, но не бренд: фирменной палитры у него нет, и в
`palettes.BRAND_PROTOTYPES` он не появляется. Цветовые признаки по-прежнему меряют
близость к трём телеком-палитрам, а «ни на что не похоже» модель выводит сама.
"""

TASK = paths.CLASSIFICATION

UNSURE = "не уверен"

TELECOM_BRANDS = ("beeline", "megafon", "mts", "tele2", "volna", "miranda", "plus7")
"""Бренды-цели для мониторинга наружки.

Шире, чем `BRANDS`: обученный классификатор знает три из них, а VLM спросить
можно сразу про все. Папки кадров в `raw/` называются этими же словами.
WIN mobile — дочерний бренд Волны и считается ею. Виртуальные операторы банков
(СберМобайл, Т-Мобайл, Альфа-Мобайл) сюда намеренно не входят — они носят
айдентику своего банка, и отделить их от него можно только по слову на щите.
"""

